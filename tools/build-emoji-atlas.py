#!/usr/bin/env python3
"""Build the shipped WoW textures from a local, pinned Twemoji archive (Pillow 13).

Download SOURCE_URL, then run: python3 tools/build-emoji-atlas.py path/to/twemoji.tar.gz
The build reads PNGs and the graphics license only. Normal add-on builds use the output.
"""

import argparse
import hashlib
import io
import re
import tarfile
from pathlib import Path

from PIL import Image


REVISION = "b6b55fef1e8636b540a6d016a4729ca8cdf2e60b"
VERSION = "17.0.3"
SOURCE_URL = f"https://codeload.github.com/jdecked/twemoji/tar.gz/{REVISION}"
ARCHIVE_SHA256 = "705d79de1460e5e775f362f0d0f01fbe3ef8d65bf4648c490e4649704584f747"
PAGE = 1024
CELL = 32
GUTTER = 1
SIDE = PAGE // CELL
ART = CELL - 2 * GUTTER
ADDON = Path(__file__).resolve().parents[1] / "looking-for-guidance"


def read_source(archive):
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise ValueError(f"Expected Twemoji {VERSION} from {SOURCE_URL}")
    root = f"twemoji-{REVISION}/"
    png = re.compile(re.escape(root) + r"assets/72x72/([0-9a-f]+(?:-[0-9a-f]+)*)\.png")
    graphics = {}
    license_text = b""
    with tarfile.open(archive, "r|gz") as source:
        for entry in source:
            if not entry.isfile():
                continue
            if entry.name == root + "LICENSE-GRAPHICS":
                license_text = source.extractfile(entry).read()
            match = png.fullmatch(entry.name)
            if match:
                key = tuple(int(cp, 16) for cp in match[1].split("-") if cp != "fe0f")
                if key in graphics:
                    raise ValueError(f"Conflicting canonical emoji {key}")
                graphics[key] = source.extractfile(entry).read()
    if len(graphics) != 4009 or not license_text.startswith(b"Attribution 4.0 International"):
        raise ValueError("Could not find the pinned release artwork and license")
    return graphics, license_text


def build(archive):
    graphics, license_text = read_source(archive)
    media = ADDON / "Media"
    out = media / "Emoji"
    out.mkdir(exist_ok=True)
    (media / "CC-BY-4.0-Twemoji.txt").write_bytes(license_text)
    notice = f"""Twemoji {VERSION} graphics
Artwork by Twitter and the Twemoji contributors, including Jason Sofonia
and Justine De Caires.
Source: https://github.com/jdecked/twemoji/tree/{REVISION}
Contributors: https://github.com/jdecked/twemoji/graphs/contributors
License: Creative Commons Attribution 4.0 International (CC BY 4.0)
https://creativecommons.org/licenses/by/4.0/
The full license is in CC-BY-4.0-Twemoji.txt.

Looking for Guidance resizes the original 72x72 PNG graphics to 30x30 pixels,
adds a transparent gutter and arranges them into 32-bit TGA texture atlases.
"""
    (media / "NOTICE-Twemoji.txt").write_text(notice, encoding="utf-8")
    lua = [
        f"-- Generated by tools/build-emoji-atlas.py from Twemoji {VERSION}.",
        "local _, T = ...",
        "T.EmojiAtlas = {",
        f"    size={PAGE}, cell={CELL}, gutter={GUTTER}, columns={SIDE}, rows={SIDE},",
        r'    prefix="Emoji\\Page", suffix=".tga", pageFormat="%02d", firstPage=1,',
        "}",
        "T.EmojiIndex = {",
    ]
    ordered = sorted(graphics)
    for start in range(0, len(ordered), SIDE * SIDE):
        page_id = start // (SIDE * SIDE) + 1
        atlas = Image.new("RGBA", (PAGE, PAGE))
        for tile, key in enumerate(ordered[start : start + SIDE * SIDE]):
            with Image.open(io.BytesIO(graphics[key])) as original:
                if original.size != (72, 72):
                    raise ValueError(f"Unexpected source size {original.size} for {key}")
                rgba = original.convert("RGBA").resize((ART, ART), Image.Resampling.LANCZOS)
            atlas.paste(rgba, ((tile % SIDE) * CELL + GUTTER, (tile // SIDE) * CELL + GUTTER))
            chars = "".join(chr(cp) for cp in key)
            lua.append(f'    ["{chars}"]={start + tile},')
        atlas.save(out / f"Page{page_id:02}.tga", orientation=1)
    lua.append("}\n")
    (ADDON / "EmojiData.lua").write_text("\n".join(lua), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    build(parser.parse_args().archive)
