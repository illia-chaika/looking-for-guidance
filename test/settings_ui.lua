-- Exercise one draft across the real modal, its preview, resize and Escape lifecycle.
local here = arg[0]:match("^(.*)[/\\][^/\\]+$") or "."
local wow = dofile(here .. "/wow.lua")
wow.payload = wow.Samples(here .. "/../samples/samples.json").payloads.ready
local T = wow.Load(here .. "/../looking-for-guidance")
T.Window.Show()
local function frame(match)
    for _, f in ipairs(wow.frames) do if f:IsVisible() and match(f) then return f end end
    error("control is not visible")
end
local function named(caption)
    return frame(function(f) return (f.label and f.label:GetText() == caption) or (f.text and f.text:GetText() == caption) end)
end
local function gear()
    return frame(function(f) return f.glyph and f.glyph.name == "gear" end)
end
local function esc()
    -- Blizzard uses global names in UISpecialFrames for Escape.
    _G[UISpecialFrames[#UISpecialFrames]]:Hide()
end
gear():Fire("OnClick")
local panel = _G.looking_for_guidance_settings_panel
local veil = panel:GetParent()
assert(veil:GetParent() == UIParent and veil:IsVisible() and veil:IsMouseEnabled())
assert(veil:GetFrameStrata() == "FULLSCREEN_DIALOG" and panel:GetFrameStrata() == veil:GetFrameStrata())
assert(panel:IsMouseEnabled() and panel:GetFrameLevel() > veil:GetFrameLevel(), "fullscreen mouse shield must be below the settings dialog")
assert(named("Отмена"):GetFrameLevel() > panel:GetFrameLevel())
assert(panel:GetWidth() == 790 and panel:IsVisible() and not named("Сохранить"):IsEnabled())
named("Диалог"):Fire("OnClick")
assert(T.settings.appearance == "journal" and named("Сохранить"):IsEnabled())
named("Данные персонажа"):Fire("OnClick")
named("Снять все"):Fire("OnClick")
named("Персонаж"):Fire("OnClick")
named("Посмотреть данные"):Fire("OnClick")
assert(_G.looking_for_guidance_data_preview:IsVisible() and UISpecialFrames[#UISpecialFrames] == "looking_for_guidance_data_preview")
assert(looking_for_guidance_data_preview:GetParent() == panel and looking_for_guidance_data_preview:GetFrameLevel() > named("Сохранить"):GetFrameLevel())
esc()
assert(panel:IsVisible() and UISpecialFrames[#UISpecialFrames] == "looking_for_guidance_settings_panel")
named("Уведомления"):Fire("OnClick")
named("Звук, когда ответ готов"):Fire("OnClick")
UIParent:SetSize(390, 540)
wow.Event("DISPLAY_SIZE_CHANGED")
assert(panel:GetWidth() <= 390 and panel:GetHeight() <= 540)
named("Данные персонажа"):Fire("OnClick")
local _, _, _, firstX, firstY = named("Персонаж"):GetParent():GetPoint(1)
local _, _, _, secondX, secondY = named("Заклинания"):GetParent():GetPoint(1)
assert(firstX == secondX and secondY < firstY and named("Персонаж"):GetWidth() <= 390)
esc()
assert(looking_for_guidance_window:IsVisible() and not panel:IsShown() and tContains(UISpecialFrames, "looking_for_guidance_window"))
assert(not veil:IsVisible(), "Escape must release mouse input to WoW")
assert(T.settings.appearance == "journal" and T.settings.context.gear and T.settings.alertSound)
gear():Fire("OnClick")
named("Трекер"):Fire("OnClick")
T.settings.choice.model = "changed-elsewhere"
-- Journal research: on click by default, automatic or with another daily cap only after Save.
frame(function(f) return f.label and f.label:GetText() == "Советник" and f:GetParent() == named("Уведомления"):GetParent() end):Fire("OnClick")
local function shown(text)
    for _, f in ipairs(wow.texts) do if f:IsVisible() and f:GetText() == text then return true end end
end
assert(shown("Исследования журнала") and shown("Советник готовит раздел, только когда ты нажмёшь в нём кнопку. Каждое исследование расходует лимит твоей подписки."))
named("Автоматически"):Fire("OnClick")
assert(not shown("Советник готовит раздел, только когда ты нажмёшь в нём кнопку. Каждое исследование расходует лимит твоей подписки."), "the hint follows the chosen mode")
local cap = frame(function(f) return f.slider and f.readout end)
assert(cap.readout:GetText() == "60")
cap.slider:Fire("OnValueChanged", 30)
assert(cap.readout:GetText() == "30" and T.settings.research == "click" and T.settings.researchCap == 60, "nothing changes before Save")
named("Сохранить"):Fire("OnClick")
assert(T.settings.appearance == "tracker" and T.settings.choice.model == "changed-elsewhere")
assert(T.settings.research == "auto" and T.settings.researchCap == 30)
assert(not veil:IsVisible())
gear():Fire("OnClick")
local function closeButton(owner)
    return frame(function(f) return f:GetParent() == owner and f.glyph and f.glyph.name == "close" end)
end
closeButton(panel):Fire("OnClick")
assert(not veil:IsVisible() and looking_for_guidance_window:IsVisible())
gear():Fire("OnClick")
named("Диалог"):Fire("OnClick")
veil:Fire("OnMouseDown")
assert(not veil:IsVisible() and T.settings.appearance == "tracker")
gear():Fire("OnClick")
named("Данные персонажа"):Fire("OnClick")
named("Посмотреть данные"):Fire("OnClick")
looking_for_guidance_window:Hide()
assert(not veil:IsVisible() and not looking_for_guidance_data_preview:IsShown())
assert(tContains(UISpecialFrames, "looking_for_guidance_window"))
print("Settings: modal mouse layers, staged preview, research mode and daily cap, resize, Escape, close button, outside click and owner cleanup OK")
